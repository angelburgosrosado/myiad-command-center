CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- Core Projects & Workspaces
CREATE TABLE IF NOT EXISTS command_projects (
  id VARCHAR(64) PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  category VARCHAR(64) NOT NULL,
  status VARCHAR(100) NOT NULL,
  priority VARCHAR(32) NOT NULL,
  live_url TEXT,
  repo_url TEXT,
  infra_target VARCHAR(255),
  summary TEXT,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- ============================================================================
-- POLSIA-STYLE AUTONOMOUS OPERATOR EXTENSIONS
-- ============================================================================

-- 1. Autonomous Goals / Strategic Roadmaps (Macro Objectives)
CREATE TABLE IF NOT EXISTS autonomous_goals (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  project_id VARCHAR(64) REFERENCES command_projects(id) ON DELETE SET NULL,
  title VARCHAR(255) NOT NULL,
  description TEXT,
  mode VARCHAR(32) DEFAULT 'supervised', -- 'supervised' (requires approval) | 'god_mode' (full autonomous 24/7 loop)
  status VARCHAR(32) DEFAULT 'planning', -- 'draft' | 'planning' | 'in_progress' | 'paused' | 'completed' | 'failed'
  progress_pct INT DEFAULT 0,
  target_deadline TIMESTAMPTZ,
  summary_deliverables TEXT,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 2. Command Tasks (Base Task Model with Autonomous Execution Fields)
CREATE TABLE IF NOT EXISTS command_tasks (
  id VARCHAR(100) PRIMARY KEY,
  project_id VARCHAR(64) NOT NULL REFERENCES command_projects(id) ON DELETE CASCADE,
  goal_id UUID REFERENCES autonomous_goals(id) ON DELETE SET NULL,
  title TEXT NOT NULL,
  demand VARCHAR(32) DEFAULT 'steady',
  done BOOLEAN DEFAULT FALSE,
  status VARCHAR(32) DEFAULT 'pending', -- 'pending' | 'in_progress' | 'approval_required' | 'completed' | 'failed' | 'blocked'
  priority VARCHAR(16) DEFAULT 'medium', -- 'low' | 'medium' | 'high' | 'critical'
  assigned_agent VARCHAR(64) DEFAULT 'orchestrator', -- 'orchestrator' | 'devops' | 'engineer' | 'researcher' | 'copywriter'
  execution_target VARCHAR(255),
  requires_approval BOOLEAN DEFAULT FALSE,
  approved_by VARCHAR(64),
  note TEXT,
  output_payload JSONB,
  execution_error TEXT,
  started_at TIMESTAMPTZ,
  completed_at TIMESTAMPTZ,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

