-- 3. Autonomous Activity & Event Stream (Live Polsia-style 24/7 Agent Feed)
CREATE TABLE IF NOT EXISTS autonomous_agent_logs (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  goal_id UUID REFERENCES autonomous_goals(id) ON DELETE CASCADE,
  task_id VARCHAR(100) REFERENCES command_tasks(id) ON DELETE CASCADE,
  agent_name VARCHAR(64) NOT NULL, -- e.g. 'PolsiaOperator', 'DevOpsSentinel', 'CodeEngineer'
  event_type VARCHAR(64) NOT NULL, -- 'thought' | 'tool_call' | 'execution_step' | 'approval_request' | 'checkpoint' | 'error' | 'success'
  message TEXT NOT NULL,
  metadata JSONB,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 4. Autonomous Artifacts (Deliverables Generated by Agents)
CREATE TABLE IF NOT EXISTS autonomous_artifacts (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  goal_id UUID REFERENCES autonomous_goals(id) ON DELETE SET NULL,
  task_id VARCHAR(100) REFERENCES command_tasks(id) ON DELETE SET NULL,
  artifact_type VARCHAR(64) NOT NULL, -- 'code' | 'markdown_report' | 'sql_patch' | 'config' | 'recap_digest'
  title VARCHAR(255) NOT NULL,
  content TEXT NOT NULL,
  file_path VARCHAR(255),
  metadata JSONB,
  version INT DEFAULT 1,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 5. Autonomous Operator Recaps (Daily Morning / Evening Briefings)
CREATE TABLE IF NOT EXISTS autonomous_recaps (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  digest_date DATE NOT NULL DEFAULT CURRENT_DATE,
  period VARCHAR(32) DEFAULT 'morning_recap', -- 'morning_recap' | 'evening_recap' | 'weekly_digest'
  tasks_completed_count INT DEFAULT 0,
  services_healthy_count INT DEFAULT 0,
  services_total_count INT DEFAULT 0,
  summary_markdown TEXT NOT NULL,
  highlights JSONB,
  delivered BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

